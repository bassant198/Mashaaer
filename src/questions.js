const categories = [
 ['الحب','الحب والمودة'],['الأمان','الأمان والاحتواء'],['الغيرة','الغيرة والحدود'],['الخلافات','الخلافات والمصالحة'],['التواصل','التواصل والتعبير'],['الذكريات','الذكريات والمواقف'],['الشخصية','الشخصية والطباع'],['الأحلام','الأحلام والطموحات'],['المستقبل','المستقبل معًا'],['الجواز','الحياة الزوجية'],['البيت','البيت والمسؤوليات'],['الفلوس','المال والقرارات'],['الأهل','الأهل والحدود'],['الأطفال','الأطفال والتربية'],['القيم','القيم والمبادئ'],['الثقة','الثقة والخصوصية'],['الاحتياج','الاحتياجات العاطفية'],['الرومانسية','الرومانسية والاهتمام'],['الصراحة','الصراحة بدون تجميل'],['المرح','المرح والمواقف الخفيفة']
];
const variants = ['بصراحة ومن غير إجابة دبلوماسية','وكأنك بتحكي لصاحبك المقرّب','مع مثال حقيقي من حياتك','من غير ما تفكر كتير قبل الإجابة','ولو كان لازم تختار إجابة واحدة فقط'];
const stems = [
 'إيه أكتر حاجة في {topic} بتفرق معاك؟',
 'إمتى آخر مرة حسيت إن {topic} كان له تأثير واضح عليك؟',
 'إيه التصرف اللي نفسك تشوفه أكتر في {topic} بينا؟',
 'إيه الحاجة اللي ممكن تضايقك في {topic} حتى لو كانت صغيرة؟',
 'لو تقدر تغيّر حاجة واحدة في {topic}، هتغيّر إيه؟',
 'إيه أكتر سوء فهم ممكن يحصل بينا بسبب {topic}؟',
 'إيه الحاجة اللي بتخليك تحس بالراحة في {topic}؟',
 'إيه الحاجة اللي صعب عليك تقولها بصوت عالي بخصوص {topic}؟',
 'لو حصل موقف كبير متعلق بـ{topic}، إيه أول رد فعل متوقع منك؟',
 'إيه توقعك من الشخص اللي بتحبه في موضوع {topic}؟',
 'إيه ذكرى نفسك نعمل واحدة شبهها مرتبطة بـ{topic}؟',
 'لو هتديني نصيحة واحدة تخص {topic} في علاقتنا، هتقول إيه؟'
];
const questions=[];let id=1;
for(let c=0;c<categories.length;c++){
 for(let s=0;s<stems.length;s++){
  for(let v=0;v<5;v++){
   const topic=categories[c][1];
   questions.push({id:id++,category:categories[c][0],topic,level:(s%5)+1,text:stems[s].replace('{topic}',topic)+' '+variants[v]});
  }
 }
}
export default questions;
